using UnityEngine;
using UnityEngine.UI;
using UnityEngine.Android;
using System;
using System.Text;

public class Mouse : MonoBehaviour
{
    
    // The default velocity of the mouse
    [SerializeField]
    public Vector3 defaultVelocity = new Vector3(1.0f, 0.0f, 0.0f);
    
    // The minimum volume of the microphone below which it will not register (0-1)
    [SerializeField]
    public float minimumVolume = 0.0f;
    // The multiplier of the microphone volume
    [SerializeField]
    public float volumeMultiplier = 25.0f;
    // The upwards velocity in case the volume is maxed out
    [SerializeField]
    public float upwardVelocity = 5.0f;
    
    // The multiplier for the velocity of other inputs
    [SerializeField]
    public float velocityMultiplier = 10.0f;
    
    // An optional panel to display the current volume
    [SerializeField]
    public Image volumePanel = null;
    
    // The number of samples to gather from the microphone each update
    public readonly int sampleWindow = 4410;
    // The length of the audioclip in seconds
    public readonly int clipLength = 1;
    // The sample frequency of the microphone
    private int _sampleFrequency;
    public readonly int sampleFrequency = 44100;
    
    // The microphone to use as input
    private string _mic;
    // The audioclip generated by the microphone constantly
    private AudioClip _clip;
    
    private bool _micInitialized = false;
    
    void Start()
    {
        // check if the app has microphone permission
        if (!Permission.HasUserAuthorizedPermission(Permission.Microphone))
        {
            // attach callbacks to the permission request
            PermissionCallbacks callbacks = new PermissionCallbacks();
            callbacks.PermissionGranted += this.OnMicrophonePermissionGranted;
            callbacks.PermissionDenied += this.OnMicrophonePermissionDenied;
            callbacks.PermissionDeniedAndDontAskAgain += this.OnMicrophonePermissionDenied;
            
            // request permission for microphone
            Permission.RequestUserPermission(Permission.Microphone, callbacks);
            
            return;
        }
        
        this.OnMicrophonePermissionGranted("");
    }
    
    void OnMicrophonePermissionDenied(string permission)
    {
        throw new InvalidOperationException("The microphone permission was denied.");
    }
    
    void OnMicrophonePermissionGranted(string permission)
    {
        this._micInitialized = true;
        
        // log all microphones
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < Microphone.devices.Length; i++)
        {
            sb.Append(Microphone.devices[i] + " | ");
        }
        Debug.Log(sb.ToString());
        
        // use default microphone
        if (Microphone.devices.Length <= 0)
            throw new ArgumentException("No microphone found.");
        this._mic = Microphone.devices[0];
        Debug.Log("Using microphone " + this._mic);
        
        // Get the supported sample frequencies from the device
        Microphone.GetDeviceCaps(this._mic, out int minFrequency, out int maxFrequency);
        this._sampleFrequency = Math.Clamp(this.sampleFrequency, minFrequency, maxFrequency);
        Debug.Log("Using sample frequency " + this._sampleFrequency);
        this._clip = Microphone.Start(this._mic, true, this.clipLength, this._sampleFrequency);
    }
    
    void OnDisable()
    {
        if (this._micInitialized)
            Microphone.End(this._mic);
    }
    
    float GetCurrentVolume()
    {
        // calculate the current position in the microphone sample
        int sample = Microphone.GetPosition(this._mic) + this.clipLength * this._sampleFrequency;
        // create array for microphone data
        float[] micData = new float[this.sampleWindow];
        // fetch the last data from the microphone
        this._clip.GetData(micData, (sample - this.sampleWindow - 1) % (this.clipLength * this._sampleFrequency));
        
        // find max peak of the sample size to use as volume
        float volume = 0;
        for (int i = 0; i < this.sampleWindow; i++)
        {
            if (micData[i] > volume)
                volume = Mathf.Abs(micData[i]);
        }
        
        return volume;
    }
    
    void Update()
    {
        if (!this._micInitialized)
            return;
        
        // get current volume
        float volume = this.GetCurrentVolume();
        volume = Mathf.Clamp(volume - this.minimumVolume, 0.0f, 1.0f - this.minimumVolume) / (1.0f - this.minimumVolume);
        volume *= this.volumeMultiplier;
        volume = Mathf.Clamp(volume, 0.0f, 1.0f);
        
        if (this.volumePanel != null) {
            RectTransform parent = this.volumePanel.transform.parent.GetComponent<RectTransform>();
            RectTransform volumePanelRect = this.volumePanel.GetComponent<RectTransform>();
            volumePanelRect.sizeDelta = new Vector2(parent.rect.width * volume, volumePanelRect.sizeDelta.y);
        }
        
        // initialize current velocity
        Vector3 velocity = this.defaultVelocity;
        
        // add microphone based velocity
        velocity += new Vector3(-volume * this.upwardVelocity, 0.0f, 0.0f);
        
        // add left/right
        // if (Input.GetKey(KeyCode.D))
        //     velocity += new Vector3(0.0f, 0.0f, this.velocityMultiplier);
        // if (Input.GetKey(KeyCode.A))
        //     velocity += new Vector3(0.0f, 0.0f, -this.velocityMultiplier);
        
        // set the current velocity
        this.GetComponent<Rigidbody>().linearVelocity = velocity;
    }
    
}